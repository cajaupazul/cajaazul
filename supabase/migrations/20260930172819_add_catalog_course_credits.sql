select source.codigo, source.nombre, source.creditos, '2026-II'
from catalog_course_credit_import as source
where not exists (
  select 1
  from public.catalog_courses as catalog
  where upper(btrim(catalog.codigo)) = upper(btrim(source.codigo))
);

-- Vincula cursos antiguos que fueron creados antes de guardar catalog_course_id.
-- El codigo oficial es la referencia estable compartida por ambos registros.
update public.courses as course
set catalog_course_id = catalog.id
from public.catalog_courses as catalog
where course.catalog_course_id is null
  and nullif(btrim(course.codigo), '') is not null
  and upper(btrim(course.codigo)) = upper(btrim(catalog.codigo));

do $$
declare
  imported_count integer;
begin
  select count(*)
  into imported_count
  from catalog_course_credit_import as source
  where exists (
    select 1
    from public.catalog_courses as catalog
    where upper(btrim(catalog.codigo)) = upper(btrim(source.codigo))
      and catalog.creditos = source.creditos
      and catalog.creditos_periodo = '2026-II'
  );

  if imported_count <> 378 then
    raise exception 'La importación de créditos quedó incompleta: % de 378 cursos.', imported_count;
  end if;
end;
$$;

commit;
